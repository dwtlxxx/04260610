/* ============================================================
 * 由音节表派生「汉字 → 拼音」与「汉字 → 首字母」两张查找表
 * 派生而非手写，避免两份数据不一致。
 * ============================================================ */

/** 汉字 → 完整拼音（不含声调） */
export const CHAR_PINYIN = (() => {
  const map = new Map();
  for (const [syllable, chars] of Object.entries(SYLLABLE_CHARS)) {
    for (const ch of chars) {
      // 同一汉字若出现在多个音节（多音字），保留先出现的读音，
      // 因为表中按字母序排列，先出现者通常是更常见的读音。
      if (!map.has(ch)) map.set(ch, syllable);
    }
  }
  return map;
})();

/** 汉字 → 拼音首字母 */
export const CHAR_INITIAL = (() => {
  const map = new Map();
  for (const [ch, syllable] of CHAR_PINYIN) map.set(ch, syllable[0]);
  return map;
})();

/** 该汉字是否在拼音表中 */
export function hasPinyin(ch) {
  return CHAR_PINYIN.has(ch);
}

/** 表中共收录多少汉字（供自检脚本核对覆盖率） */
export function pinyinTableSize() {
  return CHAR_PINYIN.size;
}
