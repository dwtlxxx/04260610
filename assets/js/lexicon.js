/** 词表集合，供切分时 O(1) 判断 */
export const TERM_SET = new Set(CAMPUS_TERMS);

/**
 * 从一段纯汉字里切出词库中的词（最长匹配，不重叠）。
 *
 * @param {string} han 纯汉字片段
 * @returns {string[]} 命中的词，按出现顺序排列
 */
export function termsIn(han) {
  const s = String(han || '');
  const out = [];
  for (let i = 0; i < s.length; i++) {
    let hit = '';
    for (let w = MAX_TERM_LEN; w >= 2; w--) {
      if (i + w > s.length) continue;
      const cand = s.slice(i, i + w);
      if (TERM_SET.has(cand)) { hit = cand; break; }
    }
    if (hit) { out.push(hit); i += hit.length - 1; }
  }
  return out;
}
