/**
 * lexicon.js —— 校园词库（用于把长句切出"可检索的词"）
 *
 * 【为什么要这个文件】
 * 数据里的字段经常是一整句中文，例如：
 *   「学生发起｜周末羽毛球约球」
 *   「意向登记不等同于最终作品提交」
 * 如果按"任意 3 字窗口"去比首字母，就会把「最终作」当成 zzz、
 * 把「学习小」当成 xxx —— 这是实际调试中出现的噪声来源。
 *
 * 正确做法是：先把长句切成"词"，再对词做拼音/首字母匹配。
 * 浏览器里没有分词器，也没有后端，所以这里用一个体积很小、
 * 只覆盖校园场景的词表（收录依据：26 条真实信息里出现的说法 +
 * 校园常见活动词），配合 logic.js 里的"最长匹配"切分使用。
 *
 * 【维护约定】
 * 1. 只收"纯汉字"词，长度 2~4 字（拼音/首字母匹配才有意义）。
 * 2. 只收校园场景里真的会被人搜的词；不收"最终""学习小组"这类
 *    通用虚词组合——它们会把噪声重新引进来。
 * 3. 新增词后必须跑 `node tools/check-search.mjs`：
 *    该脚本会检查噪声词（zzz / xxx 等）没有被词库"意外命中"。
 */

